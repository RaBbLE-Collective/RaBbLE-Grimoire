#!/usr/bin/env python3
"""P1 split manifest: joins git first-add dates, out-HEAD.txt overlap and the
Provenance Record's wave/bucket facts into a per-file table. Classification of
'influence' is a transcript fact (Provenance Record sec. 2), not the % number.
Usage: manifest.py <pocket-repo> <out-HEAD.txt> > manifest.md"""
import subprocess, sys, re, datetime, os
repo, outhead = sys.argv[1], sys.argv[2]
SDK_T = datetime.datetime(2026,10,5,16,27,40,tzinfo=datetime.timezone(datetime.timedelta(hours=-7))).timestamp()
def git(*a): return subprocess.run(['git','-C',repo,*a],capture_output=True,text=True).stdout
ov = {}
for l in open(outhead):
    p = l.rstrip('\n').split('\t')
    if p[0]=='F' and len(p)>=6: ov['firmware/'+p[1]] = (int(p[3]),float(p[5]))
files = [f for f in git('ls-files').split('\n') if f and not re.search(r'managed_components|datasheets|/build/|dependencies\.lock|^firmware/sdkconfig$|\.(png|jpg|gif|bin|a|o|obj)$',f)]
def first_add(f):
    out = git('log','--all','--follow','--diff-filter=A','--format=%at',f).split()
    return int(out[-1]) if out else None
WAVE = [('adpcm','W1'),('rabble_text','W1'),('console','W1'),('rabble_setup','W1'),('axp2101','W2'),('battery','W2'),
        ('rabble_input','W2'),('beam_text','W3'),('settings','W3'),('wifi','W3'),('rabble_audio','W4'),('voice','W4'),
        ('orbit_logic','W5'),('rabble_orbit.','W5'),('bsp_','W6'),('rabble_lcd_bands','W6'),('rabble_state','W0'),('rabble_app','W0'),
        ('lv_mem','W0'),('rabble_mem','W0'),('keypad','W0')]
INFL_BUILD = re.compile(r'(sdkconfig\.defaults|Kconfig|CMakeLists\.txt|idf_component\.yml|partitions.*\.csv)$')
def classify(f, t, pct):
    b = os.path.basename(f)
    if f.endswith('rabble_ui.c') or f.endswith('rabble_beam_score.c'):
        return 'influence','transcript: SDK counterpart read in part; never clean-roomed (W9 / W8)'
    if b=='rabble_board.h':
        return 'influence','structural echo of SDK board vtable (43.5% lines); W0 seam kept shape'
    if os.path.basename(f)=='CMakeLists.txt':
        return ('original','component registration, added before SDK') if (t is not None and t < SDK_T) else ('influence?','CMake written in/after port session; review (trivial?)')
    if INFL_BUILD.search(f) and 'nebula_lite' not in f and 'test' not in f.split('/')[:2]:
        return 'influence','build config written after reading SDK Kconfig/sdkconfig (unmeasured)'
    if 'qmi8658' in f or 'rabble_motion' in f:
        return 'original','modelled on Waveshare Apache qmi8658 component + datasheet: third-party attribution, not Meta'
    if 'nebula_lite' in f or 'rabble_render' in f:
        return 'original','<=1% overlap; nebula_lite'
    for k,w in WAVE:
        if f.startswith('firmware/') and k in b:
            return f'clean-roomed {w}','record sec. 2 mechanical bucket, redone'
    if t is not None and t < SDK_T:
        return 'original','first added before SDK (2026-10-05)'
    if pct is not None and pct>=15:
        return 'original?','post-port, overlap>=15%: review'
    return 'original','post-port own module, overlap <15%'
def side(f):
    if 'rabble_render' in f or 'nebula_lite' in f: return 'middleware (SA)'
    if f.startswith('firmware/app/RaBbLE/'):
        b=os.path.basename(f)
        if re.search(r'rabble_(clock_screen|level_screen|pomo|setup|input|shot|app)',b): return 'sdk? (generic UI; decide)'
        if b.startswith('rabble_ui'): return 'split (face to app, lifecycle to sdk)'
        return 'app (SA)'
    if 'beam_score' in f: return 'app (SA, D5)'
    if f.startswith(('firmware/drivers','firmware/boards','firmware/sdk','firmware/test','firmware/panel_bench')): return 'sdk (Apache)'
    if f.startswith('firmware/main') or f.startswith('firmware/CMake') or f.startswith('firmware/sdkconfig'): return 'app glue / build'
    return 'unscanned'
print('# RaBbLE-Pocket split manifest (P1 draft, generated)\n')
print('Generated by `cleanroom/audit-2026-11-02/scripts/manifest.py` from git first-add dates, `out-HEAD.txt` (SDK b139b45) and Provenance Record sec. 2. Statuses are heuristics keyed to transcript facts; Mark approves. `original?` = review.\n')
rows=[]
for f in sorted(files):
    t=first_add(f); o=ov.get(f); st,why=classify(f,t,o[1] if o else None)
    d=datetime.datetime.fromtimestamp(t).strftime('%Y-%m-%d') if t else '?'
    rows.append((f,side(f),st,d,f'{o[1]}%' if o else '-',why))
from collections import Counter
print('| Meta status | files |\n|---|---|')
for k,v in sorted(Counter(r[2] for r in rows).items()): print(f'| {k} | {v} |')
print('\n| path | side | Meta status | first add | overlap | basis |\n|---|---|---|---|---|---|')
for r in rows: print('| '+' | '.join(r)+' |')
